create extension if not exists btree_gist;

create table if not exists public.users (
  student_id text primary key,
  password_hash text not null,
  name text,
  is_admin boolean not null default false,
  is_active boolean not null default true,
  suspend_until timestamptz
);

alter table public.users add column if not exists must_change_password boolean not null default false;
alter table public.users add column if not exists failed_attempts integer not null default 0;
alter table public.users add column if not exists locked_until timestamptz;
alter table public.users add column if not exists created_at timestamptz not null default now();

create table if not exists public.rooms (
  id bigint generated by default as identity primary key,
  name text not null unique,
  is_active boolean not null default true
);

create table if not exists public.reservations (
  id bigint generated by default as identity primary key,
  student_id text not null references public.users(student_id) on update cascade on delete cascade,
  room_id bigint not null references public.rooms(id),
  res_date date not null,
  start_slot integer not null check (start_slot between 0 and 47),
  end_slot integer not null check (end_slot between 1 and 48 and end_slot > start_slot),
  status text not null default 'active' check (status in ('active', 'cancelled')),
  created_at timestamptz not null default now()
);

alter table public.reservations add column if not exists cancelled_at timestamptz;
alter table public.reservations add column if not exists cancelled_by text;

-- 사용자 삭제 시 예약도 함께 삭제되도록 외래키를 갱신합니다(기존 프로젝트 업그레이드용).
alter table public.reservations drop constraint if exists reservations_student_id_fkey;
alter table public.reservations
  add constraint reservations_student_id_fkey
  foreign key (student_id) references public.users(student_id)
  on update cascade on delete cascade;

create index if not exists reservations_student_date_idx
  on public.reservations (student_id, res_date)
  where status = 'active';

create table if not exists public.settings (
  key text primary key,
  value text
);

