    _fb = "[형식 배정표] 이번 생성에서는 아래 배정표의 형식을 따라 출제해주세요.\n"
    _fb += "사용할 선지 형식:\n" + af_block + "\n\n"
    _fb += "사용할 내용 형식:\n" + ct_block + "\n\n"
    _fb += "문항별 1:1 형식 배정표:\n" + assign_table + "\n\n"
