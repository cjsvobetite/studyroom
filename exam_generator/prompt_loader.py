from pathlib import Path

GUIDE_PATH = Path(__file__).resolve().parent / "prompts" / "exam_guide.md"


def load_exam_guide() -> str:
    if not GUIDE_PATH.exists():
        raise FileNotFoundError(f"{GUIDE_PATH} 없음. 셀 2를 먼저 실행.")
    return GUIDE_PATH.read_text(encoding="utf-8")


def build_system_prompt(extra: str = "", answer_formats=None, term_lang_rule: str = "") -> str:
    guide = load_exam_guide()

    # ── 최우선 지시 블록 (exam_guide보다 앞 — 모델이 가장 먼저 읽음) ──
    priority_block = ""
    if term_lang_rule.strip():
        priority_block += (
            "╔══════════════════════════════════════════════════╗\n"
            "║  🔴  의학용어 표기 규칙 — 모든 출력에 절대 우선 적용  🔴  ║\n"
            "╚══════════════════════════════════════════════════╝\n"
            f"{term_lang_rule}\n"
            "발문·선지·해설·정답표 전체에 예외 없이 적용. 어기면 출제 오류.\n\n"
        )
    if extra.strip():
        priority_block += (
            "╔══════════════════════════════════════════════════╗\n"
            "║  🟡  사용자 추가 지시 — exam_guide보다 우선 반영  🟡  ║\n"
            "╚══════════════════════════════════════════════════╝\n"
            f"{extra}\n\n"
        )

    # ── 선지 형식 오버라이드 ──
    if answer_formats:
        af_list = "\n".join(f"  - {x}" for x in answer_formats)
        format_override = (
            "[이번 요청 선지 형식 안내]\n"
            "이번 요청에서 사용할 선지 형식은 아래 목록을 기준으로 해주세요.\n"
            "exam_guide에 '유형 A(모두 고르시오)가 주력 유형'이라고 나와 있더라도,"
            "이번 요청의 선지 형식은 아래 목록이 기준입니다.\n"
            "목록에 없는 형식은 사용하지 말아 주세요.\n\n"
            f"{af_list}\n\n"
        )
    else:
        format_override = ""

    base = (
        "You are a Korean medical-school exam item writer. "
        "Follow the writing guide below STRICTLY. Output everything in Korean.\n\n"
        f"{priority_block}"
        f"{format_override}"
        "=== 출제 지침 (위 최우선 지시와 충돌 시 위 지시를 따를 것) ===\n"
        f"{guide}\n"
        "=== 끝 ===\n"
    )
    return base


def _build_assignment_table(num_mcq, num_short, answer_formats, content_types):
    """문항별 (선지형식, 내용형식, 강의 범위) 1:1 배정. 형식·범위 둘 다 강제."""
    rows = []
    REGIONS = ["전반부 (강의 첫 1/4)", "중반부-1 (2/4)", "중반부-2 (3/4)", "후반부 (4/4)"]
    for i in range(num_mcq):
        af = answer_formats[i % len(answer_formats)]
        ct = content_types[i % len(content_types)]
        region = REGIONS[i % len(REGIONS)]
        af_s = af.split(") ", 1)[1] if ") " in af else af
        ct_s = ct.split(" (", 1)[0] if " (" in ct else ct
        rows.append(f"  - 문제 {i+1}: 선지={af_s} | 내용={ct_s} | 범위={region}")
    for j in range(num_short):
        ct = content_types[j % len(content_types)]
        region = REGIONS[j % len(REGIONS)]
        ct_s = ct.split(" (", 1)[0] if " (" in ct else ct
        rows.append(f"  - 단답 S{j+1}: 선지=단답형 (1단어~1줄) | 내용={ct_s} | 범위={region}")
    return "\n".join(rows)


